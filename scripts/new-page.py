#!/usr/bin/env python3
"""Write the Astro page for an extracted board.
Usage: python3 scripts/new-page.py <key> <route-dir> <nav> "<title>" "<description>" [--three] [--astronomy] [--lang=hi]
  route-dir is relative to src/pages, e.g. "learn" or "journal/sky-guide" or "." for the root."""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); SITE = os.path.dirname(HERE)
key, route, nav, title, desc = sys.argv[1:6]
flags = sys.argv[6:]
three, astro = '--three' in flags, '--astronomy' in flags
lang = next((f.split('=')[1] for f in flags if f.startswith('--lang=')), 'en')
d = os.path.join(SITE, 'src', 'pages', route); os.makedirs(d, exist_ok=True)
depth = 1 + (0 if route == '.' else route.count('/') + 1)
up = '../' * depth
esc = lambda s: s.replace('"', '&quot;')
head = '  <script slot="head" is:inline defer src="/vendor/astronomy.browser.min.js"></script>\n' if astro else ''
langattr = f' lang="{lang}"' if lang != 'en' else ''
three_imp = "  import * as THREE from 'three';\n" if three else ''
three_set = "  (window as any).THREE = THREE;\n" if three else ''
src = f'''---
// Ported from the prototype board "{key}" (src/boards/{key}.*). Generated by scripts/new-page.py.
import BaseLayout from '{up}layouts/BaseLayout.astro';
import Board from '{up}components/Board.astro';
import tpl from '{up}boards/{key}.html?raw';
import make from '{up}boards/{key}.js';
import '{up}styles/pages/{key}.css';
---
<BaseLayout title="{esc(title)}" description="{esc(desc)}" current="{nav}"{langattr} bare>
{head}  <Board tpl={{tpl}} make={{make}} />
</BaseLayout>
<script>
{three_imp}  import {{ boot }} from '{up}lib/dc/boot.js';
  import tpl from '{up}boards/{key}.html?raw';
  import make from '{up}boards/{key}.js';
{three_set}  boot(tpl, make);
</script>
'''
open(os.path.join(d, 'index.astro'), 'w', encoding='utf-8').write(src)
print('wrote', os.path.join('src/pages', route, 'index.astro'))
